defmodule AshAcp.SurfaceProvider do
  @moduledoc """
  Optional host-implemented seam carrying A2UI surface descriptors.

  A2UI payloads are generated by the host (e.g. `ash_a2ui`). This library
  **never generates, validates or re-defines them** — it carries whatever JSON
  the host returns, verbatim, under the `session/update`'s `update._meta.a2ui`
  (the ACP `_meta` extension point), exactly as `ash_graphql` carries
  host-provided context.

  It is asked whenever the server sends an `available_commands_update`, with
  `meta.reason` saying why:

  * `:session_new` — right after `session/new` (usually `nil`: nothing open yet);
  * `:session_load` — on `session/load`, after the transcript replay: return
    the session's **last surface** so a resumed client shows where it was;
  * `:turn_end` — closing every prompt turn.

  Returning `nil` (or configuring no provider) simply omits the field.
  """

  @callback surface(session :: term(), meta :: map()) :: surface :: map() | nil
end
